package controllers

import "net/http"

// stripTrailer must be called by every handler that returns 204.
//
// fuego unconditionally sets `Trailer: Server-Timing` on typed routes
// (fuego@v0.19.0/serve.go:129) with no option to disable it. Announcing a trailer
// commits the response to a chunked body — but a 204 has no body, so the
// combination is invalid. Go emits it anyway; Node-based reverse proxies, Vite's
// dev proxy among them, reject it with ERR_HTTP_TRAILER_INVALID and terminate the
// process, which looks exactly like the API server having crashed.
//
// fuego sets the header before invoking the controller, so removing it here takes
// effect. The Server-Timing values still go out as ordinary headers.
func stripTrailer(w http.ResponseWriter) {
	w.Header().Del("Trailer")
}

// forceJSON must be called by every handler that overrides the status code.
//
// When OptionDefaultStatusCode is used, fuego writes the status before its
// serializer sets a content type, so Go sniffs the body and labels JSON as
// `text/plain; charset=utf-8`. Clients generated by oazapfts then hand back the
// raw string instead of a parsed object, which surfaces as fields being
// mysteriously undefined rather than as an error. WithResponseContentType on the
// engine does not cover this path.
func forceJSON(w http.ResponseWriter) {
	w.Header().Set("Content-Type", "application/json")
}
